def extract_entities_and_graph(text, ia_agent, output_filename="grafo.html"):
    """
    Uses AI to analyze text, extract relationships between entities (people, organizations, locations, domains, emails),
    and generates an interactive graph using Pyvis.
    
    Args:
        text (str): Source text for the analysis.
        ia_agent (IAAgent): AI Agent logic.
        output_filename (str): Name of the generated HTML file.
        
    Returns:
        str: Full path to the generated HTML file, or None if it fails.
    """
    output_filename = os.path.join(DIR_GRAPHS, os.path.basename(output_filename))
    if not text:
        print("[bold red]No text to analyze.[/bold red]")
        return None

    max_chars = 25000 
    if len(text) > max_chars:
        text = text[:max_chars] + "... [Text truncated]"

    prompt = f'''
    Act as an OSINT Intelligence Analyst. Read the following text and extract the relationships between different entities.
    An entity can be a Person, an Organization, a Location, a Website/Domain, an Email, or a Technology.
    
    I need you to return ONLY a list of relationships in plain text with exactly this format, one relationship per line:
    [Entity 1] | [Type of entity 1] | [Relationship description] | [Entity 2] | [Type of entity 2]
    
    Example:
    John Doe | Person | works at | Tech Corp | Organization
    Tech Corp | Organization | located in | New York | Location
    admin@example.com | Email | belongs to | John Doe | Person
    
    Do NOT use Markdown blocks. DO NOT write anything other than the list with the pipe (|) separators.
    If you find no relationships, respond with "NO_RELATIONSHIPS".
    
    Source Text:
    {text}
    '''

    try:
        response_text = ia_agent.generator.generate(prompt)
        if not response_text or response_text.strip() == "NO_RELATIONSHIPS":
            print("[yellow]No sufficient entities were identified for the graph.[/yellow]")
            return None
            
        # 2. Parse the AI response and build the graph
        # Create the network, configuring physics for a better layout
        net = Network(height="750px", width="100%", bgcolor="#222222", font_color="white", directed=True)
        
        # Assign colors to groups (Entity types)
        color_map = {
            'Persona': '#E57373', 'Person': '#E57373',
            'Organización': '#64B5F6', 'Organization': '#64B5F6',
            'Ubicación': '#81C784', 'Location': '#81C784',
            'Dominio': '#FFD54F', 'Website': '#FFD54F', 'Domain': '#FFD54F',
            'Email': '#BA68C8',
            'Tecnología': '#4DB6AC', 'Technology': '#4DB6AC'
        }
        
        lines = response_text.strip().split('\n')
        nodes_added = set()
        edges_added = 0
        
        for line in lines:
            parts = [p.strip() for p in line.split('|')]
            # Make sure the line has exactly 5 parts to consider it valid
            if len(parts) == 5:
                e1, t1, relation, e2, t2 = parts
                
                # Default colors if the type is not exactly recognized
                c1 = color_map.get(t1, "#FFFFFF")
                c2 = color_map.get(t2, "#FFFFFF")
                
                # Add nodes if they haven't been added yet
                if e1 not in nodes_added:
                    net.add_node(e1, label=e1, title=t1, color=c1)
                    nodes_added.add(e1)
                
                if e2 not in nodes_added:
                    net.add_node(e2, label=e2, title=t2, color=c2)
                    nodes_added.add(e2)
                
                # Add relationship (Edge)
                net.add_edge(e1, e2, title=relation, label=relation, color="#aaaaaa")
                edges_added += 1

        if edges_added == 0:
            print("[yellow]No relationships were identified to build the graph.[/yellow]")
            return None

        net.save_graph(output_filename)
        print(f"[green]Graph saved to:[/green] {output_filename}")
        return output_filename

    except Exception as e:
        print(f"[bold red]Error during entity extraction and graph generation:[/bold red] {e}")
        return None

