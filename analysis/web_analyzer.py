def get_text_from_url(url):
    """
    Extracts and cleans the text content of a webpage.

    This function downloads the HTML of a URL, parses it with BeautifulSoup,
    and removes non-visible elements (like scripts and styles) to leave
    only the readable text.

    Args:
        url (str): The web address to extract text from.

    Returns:
        str: The clean text of the webpage, or None if an error occurs.
    """
    try:
        # User-Agent headers are set to simulate a real browser.
        # This helps avoid blocks from websites that reject basic automated requests.
        headers = {
            'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/91.0.4472.124 Safari/537.36'
        }
        # Performs an HTTP GET request to the URL.
        # The timeout ensures the program doesn't hang indefinitely if the server doesn't respond.
        response = requests.get(url, headers=headers, timeout=15)
        # Raises an exception for HTTP error codes (e.g., 404 Not Found, 500 Internal Server Error).
        response.raise_for_status()
        
        # Initializes BeautifulSoup to parse the HTML using the standard 'html.parser'.
        soup = BeautifulSoup(response.text, 'html.parser')
        
        # Finds and removes all <script> and <style> tags, as their content is not readable text.
        for script_or_style in soup(["script", "style"]):
            script_or_style.decompose()  # decompose() completely deletes the element from the tree.
            
        # Extracts all text from the cleaned HTML.
        text = soup.get_text()
        
        # Processes the text to improve readability:
        # 1. Separates the text by lines and removes spaces at the beginning and end of each line (strip).
        lines = (line.strip() for line in text.splitlines())
        # 2. Separates lines by multiple spaces and strips again.
        chunks = (phrase.strip() for line in lines for phrase in line.split("  "))
        # 3. Joins the non-empty fragments with a line break.
        clean_text = '\n'.join(chunk for chunk in chunks if chunk)
        
        return clean_text
    except requests.exceptions.RequestException as e:
        # Captures and logs any error during the extraction process (network issues, invalid URL, etc.).
        print(f"Error extracting text from {url}: {e}")
        return None
    except Exception as e:
        # Captures any other unexpected error during the process.
        print(f"An unexpected error occurred while processing the URL: {e}")
        return None

def _build_summary_prompt(text):
    """
    Helper function to build the prompt for text summarization.
    """
    return f"Please summarize the following text extracted from a webpage:\n\n---\n{text}\n---"

def summarize_text_with_ia(text, ia_agent):
    """
    Uses an AI Agent to generate a summary of the provided text.

    Args:
        text (str): The text to summarize.
        ia_agent (IAAgent): The initialized AI agent.

    Returns:
        str: The summary generated by the AI, or an error/warning message.
    """
    if not text:
        return "No text provided for summarization."

    # Limits the text size to avoid exceeding the AI model's token limit.
    # 30,000 characters is a safe approximation for current limits.
    max_chars = 30000 
    if len(text) > max_chars:
        # Truncates the text and adds a notice.
        text = text[:max_chars] + "... [Text truncated, too long]"

    try:
        # Generates the prompt and calls the AI agent's generate text method.
        prompt = _build_summary_prompt(text)
        summary = ia_agent.generator.generate(prompt)
        return summary if summary else "Could not generate a summary."
    except Exception as e:
        return f"Error interacting with the AI: {e}"

